#pragma once
// ============================================================
//  Hooks/Hooks.h —— 挂钩层（**只做触发，不写任何逻辑**）
// ------------------------------------------------------------
//  【本层的唯一铁律】
//  Hooked_PaintTraverse 内部**只允许**出现一行：
//      ESP::Render();
//  Hooked_CreateMove     内部**只允许**出现一行：
//      Aimbot::CreateMove(pCmd, sampleTime);
//  任何 if / 循环 / 读内存 / 算角度出现在这里都是架构腐化，
//  都会让"功能逻辑"与"触发时机"重新耦合，等于回到旧结构。
//
//  【为什么值得这么严格】
//  旧结构里 CreateMove 钩子里混着：无扩散改写、连跳判定、
//  候选收集、角度求解、过检测三件套、MoveFix 回写 —— 783 行里
//  只有几十行是"钩子该做的事"。拆开之后，改Aimbot 完全不需要
//  看 Hooks.cpp，反之亦然。
//
//  【依赖方向】Hooks 位于依赖图最上层（L4），只向下依赖。
//  没有任何东西可以 include 本文件（main.cpp 除外）。
// ============================================================

#include <Windows.h>
#include <cstdint>

namespace Hooks
{
    // ============================================================
    //  生命周期
    // ============================================================
    bool Init();      // 挂全部钩子；失败项跳过并打日志
    void Shutdown();  // 还原全部钩子（卸载路径）

    // ============================================================
    //  三个挂钩点
    // ------------------------------------------------------------
    //  ① PaintTraverse —— 绘制帧（DX9 EndScene 或 Present）
    //     作用：把整帧的绘制事务开起来，交给 ESP。
    //  ② CreateMove   —— 逻辑帧（客户端主循环，66tick/s）
    //     作用：把已填充的 CUserCmd 交给自瞄。
    //  ③ FrameEnd     —— 可选（如需 overlay 的 present 双写）
    //
    //  ⚠ 钩子函数原型刻意用 **void* / 裸类型**，不出现任何引擎类型：
    //    这样 Hooks.h 不需要 include 引擎 SDK，依赖图才不会被拖成环。
    // ============================================================

    // ---- 内部：原函数 trampoline 指针（.cpp 内静态，本头不暴露）----
    //  例：CreateMove 现在走 **vtable[27] 手写跳板**，不是 MinHook。
    //      若改用 MinHook，trampoline 由MH_CreateHook 返回，形状一致。

    // ============================================================
    //  诊断
    // ------------------------------------------------------------
    struct Status
    {
        bool paint    = false;   // 绘制钩子是否已挂
        bool createMove = false; // CreateMove 是否已挂
        bool frameEnd = false;
        uintptr_t  target = 0;   // 挂钩目标地址
        uintptr_t  trampoline = 0;
    };
    Status GetStatus();

    // 是否处于稳定的可渲染状态（所有前置就绪）
    bool Ready();
}
