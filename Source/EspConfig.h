#pragma once
// ============================================================
// EspConfig —— ESP 设置持久化（esp_config.json，JSON 格式）
// ------------------------------------------------------------
// · 配置文件位于 DLL 同目录（esp_config.json），保存 ESP 开关、
//   绘制样式（血条大小/方框粗细等）、颜色与自瞄（含移动预判）
//   设置；结构：{ "esp": {...}, "aim": {...}, "colors": {...} }；
// · 启动（首次渲染帧）自动读取并应用；菜单修改后自动保存；
// · 热加载：外部编辑保存 JSON 后 ~1s 内自动应用（文件写时间
//   轮询；自身写盘被识别并跳过，不回环）；解析失败保留现值；
// · 兼容迁移：首次运行若仅有旧版 esp_config.ini 自动导入并
//   生成 JSON（INI 文件保留不动）；
// · 检测与保存不阻塞渲染：逐帧轻量快照比对，改动停止后由
//   独立保存线程写盘（先写 .tmp 再原子替换，防写坏配置）；
// · 文件缺失或条目非法时使用默认值，并记录警告到 payload.log。
// ============================================================

// 读取并应用配置文件（缺少文件/条目非法时保留默认值并记录警告）
void EspConfigLoad();

// 每渲染帧调用：热加载轮询 + 设置改动检测（快照比对），改动停止后异步保存
void EspConfigTick();

// 立即同步保存当前设置（卸载/退出前调用，确保不丢改动）
void EspConfigSaveNow();
