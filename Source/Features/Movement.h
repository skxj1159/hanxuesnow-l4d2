#pragma once
// ============================================================
//  Features/Movement.h —— 自动连跳 / 自动连发（独立模块）
// ------------------------------------------------------------
//  【设计原则：与检测/限制逻辑完全解耦】
//   本模块【只写 CUserCmd 的 buttons 位】，不读不改任何检测状态、
//   不参与任何"规避"判定、不被自瞄/静默依赖。调用方式是一条
//   独立入口 Movement::CreateMove(cmd)，与 Aimbot::CreateMove
//   平级、互不引用。谁先谁后都不影响正确性。
//
//  【为什么独立成文件而不是塞进 Aimbot.cpp】
//   Aimbot.cpp 已 2190 行，且它承担引擎 vcall、骨骼/命中盒解析、
//   静默架构三条主线。再往里塞输入时序逻辑会让"瞄准"和"操作"
//   互相牵连——任一条出问题都要排查整个文件。分开后，连跳连发
//   出问题只需看这一个文件。
//
//  【落点】Hooks.cpp 的 Hooked_CreateMove 里，Aimbot::CreateMove
//  调用之后各调一次。改动集中在一个调用点，回滚成本 = 删两行。
// ============================================================

#include "../SDK/Cmd.h"

namespace Movement
{
    // ============================================================
    //  CreateMove —— 每 tick 调用一次
    // ------------------------------------------------------------
    //  · 自动连跳：按住空格时，落地沿触发 IN_JUMP 上升沿
    //  · 自动连发：按住 IN_ATTACK 时按固定间隔补齐攻击脉冲
    //               （按住 IN_USE/E 时暂停，避免干扰药品）
    //
    //  两者都只操作 buttons 位，绝不改动 viewangles / move 数值，
    //  因此与平滑/静默/移动修正完全正交。
    // ============================================================
    void CreateMove(sdk::CUserCmd* cmd);

}